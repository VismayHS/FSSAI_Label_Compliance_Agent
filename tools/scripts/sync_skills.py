"""Vendor, update and install the shared AI-assistant skills. See tools/skills/README.md.

    python tools/scripts/sync_skills.py vendor [--source NAME]   # re-copy tools/skills/vendor/ from the pinned commits
    python tools/scripts/sync_skills.py update [--source NAME]   # move the pins to upstream HEAD, then vendor
    python tools/scripts/sync_skills.py install                  # copy the curated set into .claude/skills and .claude/agents
    python tools/scripts/sync_skills.py check                    # fail if tools/skills/vendor/ differs from the manifest

Upstream repos are fetched as sparse, blob-less clones of exactly the paths in
tools/skills/manifest.json, so large repos (React Bits is ~700 MB) cost a few MB.
Nothing from upstream is executed.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SKILLS = ROOT / "tools" / "skills"
MANIFEST = SKILLS / "manifest.json"
VENDOR = SKILLS / "vendor"
PROJECT = SKILLS / "project"
CLAUDE = ROOT / ".claude"
INSTALLED_LOG = CLAUDE / "skills" / ".installed-by-sync_skills.json"


def git(*args: str, cwd: Path) -> str:
    result = subprocess.run(("git", "-c", "core.longpaths=true", *args), cwd=cwd, text=True,
                            capture_output=True, encoding="utf-8")
    if result.returncode:
        sys.exit(f"git {' '.join(args)} failed:\n{result.stderr.strip()}")
    return result.stdout


def load_manifest() -> dict:
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def selected(manifest: dict, name: str | None) -> dict:
    sources = manifest["sources"]
    if name and name not in sources:
        sys.exit(f"unknown source '{name}'. Known: {', '.join(sources)}")
    return {name: sources[name]} if name else sources


def checkout(src: dict, workdir: Path) -> Path:
    """Sparse, blob-less checkout of only the manifest's paths at the pinned commit."""
    patterns = [f"/{p}" for p in src["copy"].values()]  # gitignore syntax: matches a file or a whole folder
    if "catalog" in src:
        patterns.append(f"/{src['catalog']['registry']}/*-{src['catalog']['flavor']}.json")
    git("init", "-q", cwd=workdir)
    git("config", "core.autocrlf", "false", cwd=workdir)  # copy upstream bytes as they are
    git("remote", "add", "origin", src["repo"], cwd=workdir)
    git("sparse-checkout", "set", "--no-cone", *patterns, cwd=workdir)
    git("fetch", "-q", "--depth", "1", "--filter=blob:none", "origin", src["commit"], cwd=workdir)
    git("checkout", "-q", "FETCH_HEAD", cwd=workdir)
    return workdir


def copy_paths(src: dict, repo: Path, dest: Path) -> None:
    for target, upstream in src["copy"].items():
        source = repo / upstream
        if not source.exists():
            sys.exit(f"{src['repo']}@{src['commit'][:7]} has no '{upstream}'")
        out = dest / target
        out.parent.mkdir(parents=True, exist_ok=True)
        if source.is_dir():
            shutil.copytree(source, out)
        else:
            shutil.copy2(source, out)


def write_catalog(src: dict, repo: Path, dest: Path) -> None:
    """React Bits: one row per component of the chosen flavor, with its install command."""
    cat = src["catalog"]
    category_of = {}
    for category in git("ls-tree", "--name-only", f"HEAD:{cat['categories']}", cwd=repo).split():
        for component in git("ls-tree", "--name-only", f"HEAD:{cat['categories']}/{category}", cwd=repo).split():
            category_of[component] = category
    rows = []
    for item in sorted((repo / cat["registry"]).glob(f"*-{cat['flavor']}.json")):
        data = json.loads(item.read_text(encoding="utf-8"))
        rows.append({
            "name": data["title"],
            "category": category_of.get(data["title"], "Other"),
            "description": data.get("description", "").strip(),
            "dependencies": data.get("dependencies", []),
            "registry_item": data["name"],
            "install": f"npx shadcn@latest add @react-bits/{data['name']}",
            "files": [f["path"] for f in data.get("files", [])],
        })
    (dest / "catalog.json").write_text(json.dumps(rows, indent=2) + "\n", encoding="utf-8", newline="\n")
    lines = [
        "# React Bits catalog",
        "",
        f"Generated by `tools/scripts/sync_skills.py` from {src['repo']} at `{src['commit'][:7]}` "
        f"({len(rows)} components, flavor `{cat['flavor']}` = TypeScript + plain CSS).",
        "How to choose and add one: `tools/skills/project/react-bits/SKILL.md`.",
        "",
    ]
    for category in sorted({r["category"] for r in rows}):
        lines += [f"## {category}", "", "| Component | What it does | npm dependencies |", "|---|---|---|"]
        for r in (r for r in rows if r["category"] == category):
            deps = ", ".join(f"`{d}`" for d in r["dependencies"]) or "none"
            lines.append(f"| `{r['name']}` | {r['description'].replace('|', '/')} | {deps} |")
        lines.append("")
    (dest / "CATALOG.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")


def write_sources(manifest: dict) -> None:
    lines = [
        "# Sources",
        "",
        "Generated by `tools/scripts/sync_skills.py` from `tools/skills/manifest.json`. Each folder under",
        "`tools/skills/vendor/` is an unmodified copy of the listed upstream paths, with that project's licence.",
        "",
        "| Folder | Upstream | Commit | Licence |",
        "|---|---|---|---|",
    ]
    for name, src in manifest["sources"].items():
        url = f"{src['repo']}/tree/{src['commit']}"
        lines.append(f"| `vendor/{name}/` | {src['repo']} | [`{src['commit'][:7]}`]({url}) | {src['license']} |")
    (SKILLS / "SOURCES.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def vendor(manifest: dict, name: str | None) -> None:
    for source_name, src in selected(manifest, name).items():
        print(f"vendor {source_name} @ {src['commit'][:7]}")
        with tempfile.TemporaryDirectory(prefix="skills-") as tmp:
            repo = checkout(src, Path(tmp))
            dest = VENDOR / source_name
            if dest.exists():
                shutil.rmtree(dest)
            dest.mkdir(parents=True)
            copy_paths(src, repo, dest)
            if "catalog" in src:
                write_catalog(src, repo, dest)
    write_sources(manifest)


def update(manifest: dict, name: str | None) -> None:
    for source_name, src in selected(manifest, name).items():
        head = git("ls-remote", src["repo"], "HEAD", cwd=ROOT).split()[0]
        print(f"{source_name}: {src['commit'][:7]} -> {head[:7]}")
        src["commit"] = head
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")
    vendor(manifest, name)


def install_skill(source: Path, target: Path, rename: str | None) -> None:
    shutil.copytree(source, target)
    if rename:
        skill_md = target / "SKILL.md"
        text = skill_md.read_text(encoding="utf-8")
        skill_md.write_text(re.sub(r"(?m)^name:.*$", f"name: {rename}", text, count=1), encoding="utf-8", newline="")


def install(manifest: dict) -> None:
    """Copy project skills and the curated vendored set into .claude/ (gitignored, rebuilt each run)."""
    skills_dir, agents_dir = CLAUDE / "skills", CLAUDE / "agents"
    previous = json.loads(INSTALLED_LOG.read_text(encoding="utf-8")) if INSTALLED_LOG.exists() else {}
    for rel in previous.get("skills", []):
        shutil.rmtree(skills_dir / rel, ignore_errors=True)
    for rel in previous.get("agents", []):
        (agents_dir / rel).unlink(missing_ok=True)
    skills_dir.mkdir(parents=True, exist_ok=True)
    agents_dir.mkdir(parents=True, exist_ok=True)

    plan: list[tuple[Path, str, str | None]] = [(p.parent, p.parent.name, None) for p in sorted(PROJECT.glob("*/SKILL.md"))]
    agents: list[Path] = []
    for source_name, src in manifest["sources"].items():
        for entry in src["install"]:
            rel, rename = (entry["path"], entry["as"]) if isinstance(entry, dict) else (entry, None)
            plan.append((VENDOR / source_name / rel, rename or Path(rel).name, rename))
        agents += [VENDOR / source_name / rel for rel in src["agents"]]

    names = [folder for _, folder, _ in plan]
    clashes = sorted({n for n in names if names.count(n) > 1})
    if clashes:
        sys.exit(f"two skills would install as the same name: {', '.join(clashes)}. Add an 'as' rename in the manifest.")
    for source, folder, rename in plan:
        if not (source / "SKILL.md").exists():
            sys.exit(f"{source} has no SKILL.md. Run `python tools/scripts/sync_skills.py vendor` first.")
        if (skills_dir / folder).exists():
            sys.exit(f".claude/skills/{folder} already exists and was not installed by this script. Rename or remove it.")
        install_skill(source, skills_dir / folder, rename)
    for agent in agents:
        shutil.copy2(agent, agents_dir / agent.name)

    INSTALLED_LOG.write_text(json.dumps({"skills": names, "agents": [a.name for a in agents]}, indent=2), encoding="utf-8", newline="\n")
    print(f"installed {len(plan)} skills into .claude/skills and {len(agents)} agents into .claude/agents")


def check(manifest: dict) -> None:
    missing = [f"vendor/{n}/{t}" for n, s in manifest["sources"].items() for t in s["copy"] if not (VENDOR / n / t).exists()]
    if missing:
        sys.exit("missing from tools/skills/vendor/ (run `python tools/scripts/sync_skills.py vendor`):\n  " + "\n  ".join(missing))
    print("tools/skills/vendor/ matches the manifest")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=("vendor", "update", "install", "check"))
    parser.add_argument("--source", help="limit vendor/update to one source from the manifest")
    args = parser.parse_args()
    manifest = load_manifest()
    {"vendor": lambda: vendor(manifest, args.source), "update": lambda: update(manifest, args.source),
     "install": lambda: install(manifest), "check": lambda: check(manifest)}[args.command]()


if __name__ == "__main__":
    main()
