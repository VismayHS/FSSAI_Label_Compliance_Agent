"""Assemble the final report (S4.3) from each owner's section, the decision records and the incident log.

    python tools/scripts/build_report.py            # writes docs/report/REPORT.md
    python tools/scripts/build_report.py --strict   # also fails while any section is still missing (use for the final)

Sections are included verbatim with their headings moved one level down; nothing is written for a missing
section except a visible "pending" line naming its owner. Links stay valid because REPORT.md sits beside them.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REPORT_DIR = ROOT / "docs" / "report"
OUT = REPORT_DIR / "REPORT.md"

# (file, part title, owner) in reading order: LLM_Context §10.
SECTIONS = [
    ("platform-and-integration.md", "Problem, architecture and platform", "Vismay"),
    ("agent-design.md", "Agent design", "Namith"),
    ("retrieval-and-performance.md", "Retrieval and performance", "Nishkal"),
    ("verification-and-evaluation.md", "Verification and evaluation", "Vihaan"),
]

_FENCE = re.compile(r"^\s*(```|~~~)")
_STATUS = re.compile(r"\*\*Status:\*\*\s*([^·\n.,;(]+)", re.IGNORECASE)  # "Accepted, built (...)" -> "Accepted"
_AUTHOR = re.compile(r"\*\*(?:Author|Owner):\*\*\s*([^·\n]+)", re.IGNORECASE)


def demote(markdown: str, levels: int = 1) -> str:
    """Move every ATX heading down `levels`, leaving fenced code untouched."""
    out, fenced = [], False
    for line in markdown.splitlines():
        if _FENCE.match(line):
            fenced = not fenced
        elif not fenced and re.match(r"^#{1,6} ", line):
            line = "#" * levels + line
        out.append(line)
    return "\n".join(out)


def title_of(markdown: str) -> str:
    first = next((ln for ln in markdown.splitlines() if ln.startswith("# ")), "# (untitled)")
    return first[2:].strip()


def _field(pattern: re.Pattern, text: str) -> str:
    m = pattern.search(text)
    return m.group(1).strip().rstrip(".").strip() if m else "?"


def decisions_table(folder: Path) -> str:
    rows = ["| # | Decision | Status | Owner |", "|---|---|---|---|"]
    for path in sorted(folder.glob("[0-9][0-9][0-9]-*.md")):
        text = path.read_text(encoding="utf-8")
        number = path.name[:3]
        title = re.sub(rf"^{number}\s*[:·.\-]?\s*", "", title_of(text))
        status = _field(_STATUS, text).capitalize()
        owner = path.stem.split("-")[1].capitalize()
        rows.append(f"| {number} | [{title}](../decisions/{path.name}) | {status} | {owner} |")
    return "\n".join(rows)


def incidents_table(folder: Path) -> str:
    rows = ["| Date | Incident | Author |", "|---|---|---|"]
    for path in sorted(folder.glob("[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]-*.md")):
        text = path.read_text(encoding="utf-8")
        title = re.sub(r"^\d{4}-\d{2}-\d{2}\s*[:·\-]?\s*", "", title_of(text))
        author = _field(_AUTHOR, text)
        rows.append(f"| {path.name[:10]} | [{title}](../incidents/{path.name}) | {author} |")
    return "\n".join(rows)


def build(report_dir: Path = REPORT_DIR) -> tuple[str, list[str]]:
    """The report text, and the sections still missing."""
    docs = report_dir.parent
    parts = ["# FSSAI Label Compliance Agent: project report", "",
             "Mini Project 10, UE24AM342AA5 ML System Design & AgentOps, PESU. Team: Nishkal, Namith, Vihaan, Vismay.",
             "", "> Generated by `tools/scripts/build_report.py` from each owner's section. Edit the sections, not this file.",
             "", "## Contents", ""]
    missing = []
    for i, (name, title, owner) in enumerate(SECTIONS, 1):
        parts.append(f"{i}. [{title}](#{i}-{re.sub(r'[^a-z0-9]+', '-', title.lower()).strip('-')})")
    parts += [f"{len(SECTIONS) + 1}. [Design decisions and what was rejected](#{len(SECTIONS) + 1}-design-decisions-and-what-was-rejected)",
              f"{len(SECTIONS) + 2}. [What did not work](#{len(SECTIONS) + 2}-what-did-not-work)", ""]
    for i, (name, title, owner) in enumerate(SECTIONS, 1):
        parts += [f"## {i}. {title}", ""]
        path = report_dir / name
        if path.exists():
            body = path.read_text(encoding="utf-8").strip()
            lines = body.splitlines()
            if lines and lines[0].startswith("# "):  # the part heading above replaces the section's own title
                body = "\n".join(lines[1:]).strip()
            parts += [demote(body), ""]
        else:
            missing.append(name)
            parts += [f"> **Pending:** {owner} writes `docs/report/{name}`.", ""]
    n = len(SECTIONS)
    parts += [f"## {n + 1}. Design decisions and what was rejected", "",
              "Each record gives the context, the options considered, the decision and its consequences.", "",
              decisions_table(docs / "decisions"), "",
              f"## {n + 2}. What did not work", "",
              "Real incidents from development: what broke, how it was noticed, the cause, the fix and the lesson.", "",
              incidents_table(docs / "incidents"), ""]
    return "\n".join(parts), missing


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--strict", action="store_true", help="fail while any section is missing")
    p.add_argument("--report-dir", type=Path, default=REPORT_DIR, help=argparse.SUPPRESS)
    p.add_argument("--out", type=Path, default=OUT)
    args = p.parse_args(argv)
    text, missing = build(args.report_dir)
    args.out.write_bytes((text.rstrip() + "\n").encode("utf-8"))
    print(f"wrote {args.out.relative_to(ROOT) if args.out.is_relative_to(ROOT) else args.out}")
    for name in missing:
        print(f"  pending: docs/report/{name}")
    return 1 if args.strict and missing else 0


if __name__ == "__main__":
    sys.exit(main())
